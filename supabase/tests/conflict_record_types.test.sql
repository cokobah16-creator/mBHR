  'a nurse cannot edit a staff-account conflict, even without deciding it');

SELECT throws_ok(
  $$UPDATE public.conflict_resolutions SET status = 'ignored'
     WHERE id::text = '22220000-0000-4000-8000-0000000c0001'$$,
