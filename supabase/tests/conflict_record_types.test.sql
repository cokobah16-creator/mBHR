  'a nurse cannot close a staff-account conflict');

SELECT throws_ok(
  $$UPDATE public.conflict_resolutions
       SET entity_type = 'patients', status = 'ignored'
     WHERE id::text = '22220000-0000-4000-8000-0000000c0001'$$,
