SELECT throws_ok(
  $$UPDATE public.conflict_resolutions SET priority = 'high'
     WHERE id::text = '22220000-0000-4000-8000-0000000c0002'$$,
  '42501', 'Stock conflicts need the inventory permission',
  'a nurse cannot edit a stock conflict');

SELECT throws_ok(
  $$UPDATE public.conflict_resolutions SET status = 'ignored'
     WHERE id::text = '22220000-0000-4000-8000-0000000c0002'$$,
