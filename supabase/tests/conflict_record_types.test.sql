-- ---------------------------------------------------------------------------
SET LOCAL request.jwt.claims = '{"sub":"22220000-0000-4000-8000-000000000002","role":"authenticated"}';

SELECT throws_ok(
  $$UPDATE public.conflict_resolutions SET priority = 'high'
     WHERE id::text = '22220000-0000-4000-8000-0000000c0001'$$,
